class DcProtocolCoverageTests(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        # the audit imports the AI and client modules for real (with a ShowBase),
        # keep that out of this test session...
        with tempfile.TemporaryDirectory() as tempDir:
            outPath = os.path.join(tempDir, 'coverage.json')
            process = subprocess.run(
                [sys.executable, os.path.join(ROOT, 'tests', 'dc_coverage.py'), '--json-out', outPath],
                cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=900)
            if process.returncode != 0:
                raise AssertionError('dc coverage audit failed:\n%s' % process.stdout.decode(errors='replace')[-4000:])

            with open(outPath) as f:
                result = json.load(f)

        cls.findings = result['findings']
        cls.importErrors = result['importErrors']
        cls.report = dc_coverage.formatReport(cls.findings, cls.importErrors, ALLOWLIST)

    def testNoNewProtocolGaps(self):
        failures = []
        for kind, items in self.findings.items():
            for item in items:
                if dc_coverage.isFailure(kind, item) and not dc_coverage.isAllowed(kind, item['key'], ALLOWLIST):
                    failures.append('%s: %s' % (kind, item['key']))

        if failures:
            self.fail('%d protocol gaps are not in the allowlist:\n  %s\n\nFull report:\n%s' % (
                len(failures), '\n  '.join(failures), self.report))

    def testAllowlistIsCurrent(self):
        # entries that no longer match anything were fixed, warn so they get
        # dropped (not a failure, gaps are fixed concurrently)...
        stale = []
        for kind, entries in ALLOWLIST.items():
            keys = [item['key'] for item in self.findings.get(kind, [])]
            for pattern in entries:
                if not any(dc_coverage.isAllowed(kind, key, {kind: {pattern: ''}}) for key in keys):
                    stale.append('%s: %s' % (kind, pattern))

        if stale:
            warnings.warn('stale dc coverage allowlist entries:\n  ' + '\n  '.join(stale))

    def testEveryReasonIsOneLine(self):
        for kind, entries in ALLOWLIST.items():
            self.assertIn(kind, self.findings)
            for pattern, reason in entries.items():
                self.assertTrue(reason and '\n' not in reason, '%s: %s' % (kind, pattern))


