"""Entry point of the compiled Pirates Online Classic client.

Nuitka compiles this file as the program's __main__.  It does what the dev
launchers (darwin/start_game.command, win32/start_dev.bat) do by hand, then
starts the game exactly like ``python -m pirates.piratesbase.PiratesStart``:

1. Finds the game folder and makes it the working directory.  PiratesStart
   loads config/*.prc by relative path, general.prc names the dc files by
   relative path, and the game reads some phase files from ../resources, so
   the working directory has to be the game folder with the resources
   folder beside it.
2. Serves the config and dc files (and Panda3D's Config.prc) compiled into
   the client (poc_client_files, generated by nuitka_build.py) from memory,
   nothing on disk can change them, and points Panda3D at the plugins
   Nuitka bundled.
3. Fills in the environment the game reads (GAME_* URLs, POC_GAMESERVER)
   from config/release.env, without overriding anything already set.
4. Takes the play token from --token, POC_TOKEN, or a prompt when run from a
   terminal.
5. Sends output to a log file when there is no console to show it.

It also runs unfrozen from a checkout for testing:
``python build/client_main.py --token dev``.

Release layout it expects (nuitka_build.py makes it):

    <release>/game/       working directory: the executable
    <release>/resources/  phase_2 .. phase_5

On macOS the same two folders live in the app bundle under
Contents/Resources/ and the executable is in Contents/MacOS/.
"""

import os
import sys
import time

try:
    # generated by nuitka_build.py: the config and dc files, compiled in
    import poc_client_files
except ImportError:
    poc_client_files = None

APP_NAME = 'PiratesOnlineClassic'

# The environment variables Panda3D reads prc files (or prc settings) from.
PANDA_PRC_ENVVARS = ('PANDA_PRC_DIR', 'PRC_DIR', 'PANDA_PRC_PATH', 'PRC_PATH',
                     'PANDA_PRC_EXECUTABLE_ARGS', 'PRC_EXECUTABLE_ARGS',
                     'PANDA_PRC_EXECUTABLE_PATTERNS', 'PRC_EXECUTABLE_PATTERNS',
                     'PANDA_PRC_PATTERNS', 'PRC_PATTERNS')


def embedded_files():
    """The compiled client carries it's config and dc files rather than
    reading them from disk, where anyone could change them."""
    if poc_client_files is not None and '__compiled__' in globals():
        return poc_client_files
    return None


def is_release():
    """True only for a Nuitka-compiled release build.  The anti-debug and
    integrity measures below are off for a source checkout (they would get in
    a developer's way, and there is nothing to protect there)."""
    return '__compiled__' in globals()


def apply_anti_debug():
    """Best effort: make a debugger harder to attach to the release client.
    On macOS and Linux this asks the kernel to refuse a tracer; on Windows it
    bows out if one is already present.  This only deters casual tampering -
    anyone determined can patch it out of the binary - so it never replaces
    the server validating what the client sends.  Every call is wrapped so a
    failure here can never stop the game from starting."""
    if not is_release():
        return
    try:
        import ctypes
        if sys.platform == 'darwin':
            # PT_DENY_ATTACH (31): the kernel refuses any debugger from here on.
            libc = ctypes.CDLL('libc.dylib', use_errno=True)
            libc.ptrace(31, 0, 0, 0)
        elif sys.platform.startswith('linux'):
            # PTRACE_TRACEME (0): a process can only be traced once, so tracing
            # ourselves stops a debugger from attaching later.  If it returns
            # an error one is already attached.
            libc = ctypes.CDLL('libc.so.6', use_errno=True)
            if libc.ptrace(0, 0, 0, 0) == -1:
                show_error('Pirates Online Classic cannot run under a debugger.')
                os._exit(1)
        elif sys.platform == 'win32':
            if ctypes.windll.kernel32.IsDebuggerPresent():
                show_error('Pirates Online Classic cannot run under a debugger.')
                os._exit(1)
            present = ctypes.c_int(0)
            ctypes.windll.kernel32.CheckRemoteDebuggerPresent(
                ctypes.windll.kernel32.GetCurrentProcess(), ctypes.byref(present))
            if present.value:
                show_error('Pirates Online Classic cannot run under a debugger.')
                os._exit(1)
    except Exception:
        pass


def executable_signature():
    """A SHA-256 of the running executable, for the client to report to the
    server (see OTPClientRepository.uberZoneInterestComplete).  The server
    only logs it - a modified client can report whatever it likes - so it is a
    tripwire for a population of altered clients, not a guarantee."""
    if not is_release():
        return None
    try:
        import hashlib
        path = sys.executable or sys.argv[0]
        h = hashlib.sha256()
        with open(path, 'rb') as f:
            for chunk in iter(lambda: f.read(1 << 20), b''):
                h.update(chunk)
        return h.hexdigest()
    except Exception:
        return None


def _compiled_containing_dir():
    compiled = globals().get('__compiled__')
    if compiled is not None:
        containing = getattr(compiled, 'containing_dir', None)
        if containing:
            return containing
    return os.path.dirname(os.path.abspath(sys.argv[0]))


def find_game_dir(explicit=None):
    """The folder with config/general.prc: next to the executable, in its
    game/ subfolder, in a macOS bundle's Contents/Resources/game, or the
    current directory (a source checkout).  A client carrying it's config
    has none on disk, it's game folder holds the executable (or is the
    bundle's Contents/Resources/game)."""
    exe_dir = _compiled_containing_dir()
    candidates = []
    if explicit:
        candidates.append(explicit)
    if os.environ.get('POC_GAME_DIR'):
        candidates.append(os.environ['POC_GAME_DIR'])

    if embedded_files():
        candidates += [os.path.join(exe_dir, '..', 'Resources', 'game'), exe_dir]
        for candidate in candidates:
            if os.path.isdir(candidate):
                return os.path.realpath(candidate)
        return None
    candidates += [
        exe_dir,
        os.path.join(exe_dir, 'game'),
        os.path.join(exe_dir, '..', 'Resources', 'game'),
        os.getcwd(),
    ]
    for candidate in candidates:
        if os.path.isfile(os.path.join(candidate, 'config', 'general.prc')):
            return os.path.realpath(candidate)
    return None


def user_data_dir():
    """A per-user writable folder for logs."""
    if sys.platform == 'win32':
        base = os.environ.get('LOCALAPPDATA') or os.path.expanduser('~\\AppData\\Local')
        return os.path.join(base, APP_NAME)
    if sys.platform == 'darwin':
        return os.path.expanduser('~/Library/Logs/' + APP_NAME)
    base = os.environ.get('XDG_STATE_HOME') or os.path.expanduser('~/.local/state')
    return os.path.join(base, APP_NAME)


def redirect_output_to_log():
    """Without a console, send stdout/stderr (Python and Panda3D's C++
    notify output alike) to a log file at the file-descriptor level."""
    log_dir = os.path.join(user_data_dir(), 'logs')
    try:
        os.makedirs(log_dir, exist_ok=True)
        path = os.path.join(log_dir, 'client-%s.log' % time.strftime('%Y%m%d-%H%M%S'))
        log = open(path, 'a', buffering=1, encoding='utf-8', errors='replace')
    except OSError:
        return None
    for fd in (1, 2):
        try:
            os.dup2(log.fileno(), fd)
        except OSError:
            pass
    sys.stdout = sys.stderr = log
    return path


def has_console():
    stream = sys.stdout
    try:
        return stream is not None and stream.isatty()
    except (AttributeError, ValueError):
        return False


def load_env_text(text):
    """KEY=VALUE lines; '#' starts a comment.  Never overrides the caller's
    environment, so a launcher or the player can still set any of these."""
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        os.environ.setdefault(key.strip(), value.strip())


def load_env_file(path):
    if not os.path.isfile(path):
        return
    with open(path, encoding='utf-8') as f:
        load_env_text(f.read())


def keep_panda_to_embedded_prc():
    """Before panda3d is imported: Panda3D reads it's Config.prc (and any
    other prc file) from the folders and settings these environment variables
    name.  Point it at a folder that doesn't exist and drop the rest, the
    client loads the Config.prc it carries itself (load_embedded_panda_prc)."""
    for name in PANDA_PRC_ENVVARS:
        os.environ.pop(name, None)
    os.environ['PANDA_PRC_DIR'] = os.path.join(bundled_root(), 'no-prc-dir')


def load_embedded_panda_prc(files):
    from panda3d.core import loadPrcFileData
    for name, text in files.getPandaPrc():
        loadPrcFileData(name, text)


def mount_embedded_game_files(game_dir, files):
    """Serves the config and dc files from memory at their usual paths in the
    game folder, PiratesStart and the client repository load them through
    Panda3D's virtual file system like any other file.  config/personal.prc is
    served empty, so a file of that name on disk can't change the release
    settings either."""
    from panda3d.core import Filename, VirtualFileMountRamdisk, VirtualFileSystem
    vfs = VirtualFileSystem.getGlobalPtr()
    root = Filename.fromOsSpecific(os.path.realpath(game_dir))
    vfs.mount(VirtualFileMountRamdisk(), root, 0)

    gameFiles = files.getGameFiles()
    gameFiles['config/personal.prc'] = b''
    for name, data in gameFiles.items():
        path = Filename(root, name)
        vfs.makeDirectoryFull(Filename(path.getDirname()))
        if not vfs.writeFile(path, data, False):
            raise IOError('could not serve %s' % name)


def bundled_root():
    """Where Nuitka put the bundled files (panda3d/, DLLs).  In onefile mode
    that is the unpack folder, not the folder holding the executable."""
    return os.path.dirname(os.path.abspath(__file__))


def point_panda_at_bundle():
    """Before panda3d is imported: let Panda3D find the Config.prc and
    Confauto.prc copied from the panda3d wheel (they hold load-audio-type
    for p3ffmpeg, which the game's mp3 sounds need)."""
    if 'PANDA_PRC_DIR' in os.environ:
        return
    root = bundled_root()
    for etc in (os.path.join(root, 'panda3d', 'etc'), os.path.join(root, 'etc')):
        if os.path.isfile(os.path.join(etc, 'Config.prc')):
            os.environ['PANDA_PRC_DIR'] = etc
            return


def add_plugin_path():
    """After panda3d.core is imported, before the window opens: add the
    folders holding the display/audio plugins to plugin-path.  Panda looks
    next to libp3dtool by default; this also covers Nuitka putting the
    plugins somewhere else, and onefile's unpack folder."""
    from panda3d.core import ExecutionEnvironment, Filename, loadPrcFileData
    dirs = []
    dtool = ExecutionEnvironment.getDtoolName()
    if dtool:
        dirs.append(os.path.dirname(Filename(dtool).toOsSpecific()))
    root = bundled_root()
    dirs += [os.path.join(root, 'panda3d'), root]
    lines = []
    seen = set()
    for d in dirs:
        d = os.path.realpath(d)
        if d in seen or not os.path.isdir(d):
            continue
        seen.add(d)
        lines.append('plugin-path %s' % Filename.fromOsSpecific(d).getFullpath())
    # The same audio/video loaders Confauto.prc sets, in case it was missed.
    lines.append('load-audio-type * p3ffmpeg')
    lines.append('load-video-type * p3ffmpeg')
    loadPrcFileData('poc-bundle', '\n'.join(lines))


def show_error(message):
    print(message, file=sys.stderr)
    if sys.platform == 'win32':
        try:
            import ctypes
            ctypes.windll.user32.MessageBoxW(None, message, 'Pirates Online Classic', 0x10)
        except Exception:
            pass


def parse_args(argv):
    """--token, --server and --game-dir; everything else is left alone."""
    opts, rest = {}, []
    it = iter(argv)
    for arg in it:
        for name in ('--token', '--server', '--game-dir'):
            if arg == name:
                opts[name] = next(it, '')
                break
            if arg.startswith(name + '='):
                opts[name] = arg.split('=', 1)[1]
                break
        else:
            if arg == '--log':
                opts['--log'] = True
            else:
                rest.append(arg)
    return opts, rest


def main():
    opts, rest = parse_args(sys.argv[1:])
    sys.argv = sys.argv[:1] + rest

    console = has_console()
    log_path = None
    if not console or opts.get('--log'):
        log_path = redirect_output_to_log()

    apply_anti_debug()

    game_dir = find_game_dir(opts.get('--game-dir'))
    if game_dir is None:
        show_error('Pirates Online Classic could not find its game folder '
                   '(config/general.prc).  Reinstall the game, or set POC_GAME_DIR.')
        return 1
    os.chdir(game_dir)
    if '__compiled__' not in globals():
        # Unfrozen run from a checkout: import the game from the game folder.
        sys.path.insert(0, game_dir)

    files = embedded_files()
    if files:
        load_env_text(files.getGameFiles()['config/release.env'].decode('utf-8'))
    else:
        load_env_file(os.path.join(game_dir, 'config', 'release.env'))
    if opts.get('--server'):
        os.environ['POC_GAMESERVER'] = opts['--server']
    if opts.get('--token'):
        os.environ['POC_TOKEN'] = opts['--token']

    if not os.environ.get('POC_TOKEN'):
        if console and sys.stdin is not None and sys.stdin.isatty():
            token = input('Username / play token: ').strip()
            if token:
                os.environ['POC_TOKEN'] = token
        if not os.environ.get('POC_TOKEN'):
            show_error('No play token.  Start the game from the launcher, or run it '
                       'with --token <token> (or set POC_TOKEN).')
            return 1

    if not os.path.isdir(os.path.join(game_dir, '..', 'resources', 'phase_3')):
        print('Warning: no resources at %s' % os.path.join(game_dir, '..', 'resources'))

    print('Pirates Online Classic: game folder %s, server %s%s' % (
        game_dir, os.environ.get('POC_GAMESERVER', '(unset)'),
        (', log %s' % log_path) if log_path else ''))

    if files:
        keep_panda_to_embedded_prc()
    else:
        point_panda_at_bundle()
    import panda3d.core  # noqa: F401  (initialises the Config.prc search)
    if files:
        load_embedded_panda_prc(files)
        mount_embedded_game_files(game_dir, files)
    add_plugin_path()

    # the client reports this to the server as it's signature, see
    # OTPClientRepository.uberZoneInterestComplete / TimeManagerAI.setSignature
    signature = executable_signature()
    if signature:
        from panda3d.core import loadPrcFileData
        loadPrcFileData('poc-signature', 'signature %s' % signature)

    # Runs the whole game; returns when the window closes.
    import pirates.piratesbase.PiratesStart  # noqa: F401
    return 0


if __name__ == '__main__':
    sys.exit(main())
